/**
 * Outlines the PrivaBank wordmark from General Sans 600 so the logo renders
 * identically without the web font.
 *
 * The word is set as two parts, "Priva" and "Bank", so the site can colour them
 * separately (ink + jade). Both parts share one baseline and one viewBox.
 *
 * Writes:
 *   scripts/wordmark.json          used by scripts/export-brand.mjs
 *   src/components/ui/wordmark.ts  imported by the site
 *
 * Run: npm run brand
 */
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const font = opentype.parse(readFileSync('scripts/fonts/GeneralSans-600.ttf').buffer.slice(0));

const PARTS = ['Priva', 'Bank'];
const SIZE = 200;
const TRACK = -0.01 * SIZE; // slightly tight, reads as one word at small sizes

const n = (v) => {
  if (!Number.isFinite(v)) throw new Error('non-finite coordinate: ' + v);
  return String(Math.round(v * 100) / 100);
};

let x = 0;
let minY = Infinity;
let maxY = -Infinity;
const parts = [];

for (const word of PARTS) {
  const cmds = [];
  for (const ch of word) {
    const glyph = font.charToGlyph(ch);
    const p = glyph.getPath(x, 0, SIZE);
    const bb = p.getBoundingBox();
    minY = Math.min(minY, bb.y1);
    maxY = Math.max(maxY, bb.y2);
    for (const c of p.commands) {
      if (c.type === 'M') cmds.push(`M${n(c.x)} ${n(c.y)}`);
      else if (c.type === 'L') cmds.push(`L${n(c.x)} ${n(c.y)}`);
      else if (c.type === 'C') cmds.push(`C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`);
      else if (c.type === 'Q') cmds.push(`Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`);
      else if (c.type === 'Z') cmds.push('Z');
    }
    x += (glyph.advanceWidth / font.unitsPerEm) * SIZE + TRACK;
  }
  parts.push(cmds.join(''));
}

const width = x - TRACK;
const viewBox = `0 ${n(minY)} ${n(width)} ${n(maxY - minY)}`;
const [a, b] = parts;

writeFileSync('scripts/wordmark.json', JSON.stringify({ viewBox, a, b }, null, 2));
writeFileSync(
  'src/components/ui/wordmark.ts',
  `// PrivaBank wordmark, outlined from General Sans 600 (Fontshare, free licence)
// at -0.01em tracking. Two paths so "Priva" and "Bank" can take different colours.
// Generated by scripts/make-wordmark.mjs (npm run brand). Do not edit by hand.
export const WORDMARK_VIEWBOX = '${viewBox}';
export const WORDMARK_PATH_A =
  '${a}';
export const WORDMARK_PATH_B =
  '${b}';
`,
);

console.log('viewBox:', viewBox, '| NaN present:', (a + b).includes('NaN'));
